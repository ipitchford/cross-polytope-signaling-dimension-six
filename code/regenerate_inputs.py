#!/usr/bin/env python3
"""Optional byte-for-byte regeneration of the two graph6 inputs with genbg."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from verification_core import VerificationError, load_json, read_graph6_records, require, sha256_file, validate_manifest_schema


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parents[1]
    parser.add_argument("--data-dir", type=Path, default=root / "data")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        parser.error(f"refusing to overwrite {args.output}")
    executable = shutil.which("genbg")
    if executable is None:
        parser.error("genbg is not on PATH; supplied-input verification does not require it")
    manifest = load_json(args.data_dir / "manifest.json")
    validate_manifest_schema(manifest)
    files = {}
    with tempfile.TemporaryDirectory(prefix="cross-polytope-genbg-") as temporary:
        temporary_path = Path(temporary)
        for right_size in (5, 6):
            generated = temporary_path / f"genbg-6-{right_size}.g6"
            command = [executable, "-q", "-z", "-d1", "-l", "6", str(right_size), str(generated)]
            completed = subprocess.run(command, check=True, capture_output=True, text=True)
            records = read_graph6_records(generated, right_size)
            supplied = args.data_dir / generated.name
            generated_hash = sha256_file(generated)
            supplied_hash = sha256_file(supplied)
            require(generated_hash == supplied_hash and generated.read_bytes() == supplied.read_bytes(),
                    f"{generated.name}: regenerated bytes differ")
            files[str(right_size)] = {
                "records": len(records),
                "sha256": generated_hash,
                "byte_identical_to_supplied": True,
                "stderr": completed.stderr,
            }
    receipt = {
        "schema": "cross-polytope-six-optional-regeneration-v1",
        "verified_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "mode": "optional-genbg-byte-regeneration",
        "genbg_executable": executable,
        "manifest_nauty_version_claim": manifest["nauty_version"],
        "files": files,
        "result": "both_graph_files_regenerated_byte_identically",
        "boundary": "This checks reproducibility of enumeration bytes. The supplied-input verifier and orbit audit separately check exact classification, certificates and coverage.",
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    print(json.dumps(receipt, indent=2, sort_keys=True))


if __name__ == "__main__":
    try:
        main()
    except VerificationError as error:
        raise SystemExit(f"verification error: {error}") from error
